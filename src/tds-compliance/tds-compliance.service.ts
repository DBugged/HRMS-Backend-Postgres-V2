// Purpose: Salary TDS compliance built from the payroll snapshots — the monthly TDS statement (what must be
//   deposited, and whether it was), the quarterly TDS return data (Form 138; Form 24Q before 1-Apr-2026) with its
//   deductee-wise Annexure I and the annual salary Annexure II, challan and statement-receipt records, and the
//   per-employee Form 130 (Form 16 before 1-Apr-2026) data.
// Responsibilities: Reads finalized PayrollRun rows (including final settlements) and never recomputes tax; owns
//   TdsChallan / TdsStatement CRUD.
// Important: These are working papers prepared from payroll. The return itself must still be validated and filed
//   through the government's utility, and the certificate that is legally valid is the one generated by TRACES
//   from the filed return.
