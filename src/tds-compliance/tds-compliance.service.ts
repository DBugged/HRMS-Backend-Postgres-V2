  listStatements(taxYear: string, organizationId: string) {
    this.assertTaxYear(taxYear);
    return this.scopedPrisma.tdsStatement.findMany({
      where: { organizationId, financialYear: taxYear },
      orderBy: { quarter: 'asc' },
    });
  }

  async setStatement(
    dto: SetStatementDto,
    actor: Actor,
    organizationId: string,
  ) {
    this.assertTaxYear(dto.financialYear);
    const existing = await this.scopedPrisma.tdsStatement.findFirst({
      where: {
        organizationId,
        financialYear: dto.financialYear,
        quarter: dto.quarter,
      },
    });
    const data = {
      formType:
        dto.formType ??
        (Number(dto.financialYear.slice(0, 4)) >= 2026 ? '138' : '24Q'),
      receiptNumber: dto.receiptNumber.toUpperCase(),
      filedOn: dto.filedOn ?? null,
    };
    let row: TdsStatement;
    if (existing) {
      await this.scopedPrisma.tdsStatement.updateMany({
        where: { id: existing.id, organizationId },
        data,
      });
      row = await this.scopedPrisma.tdsStatement.findFirstOrThrow({
        where: { id: existing.id, organizationId },
      });
    } else {
      row = await this.scopedPrisma.tdsStatement.create({
        data: {
          organizationId,
          financialYear: dto.financialYear,
          quarter: dto.quarter,
          createdById: actor.id,
          ...data,
        },
      });
    }
    await this.auditLogService.log({
      actorId: actor.id,
      action: 'TDS_STATEMENT_SET',
      module: AuditModule.PAYROLL,
      organizationId,
      targetId: row.id,
      details: {
        financialYear: dto.financialYear,
        quarter: dto.quarter,
        receiptNumber: data.receiptNumber,
        previous: existing?.receiptNumber ?? null,
      },
    });
    return row;
  }

  // ── Form 130 ────────────────────────────────────────────────────────────

  async form130Data(
    employeeId: string,
    taxYear: string,
    actor: Actor,
    organizationId: string,
  ) {
    this.assertTaxYear(taxYear);
    const isHr = actor.role === Role.ADMIN || actor.role === Role.HR;
    const runs = await this.annualRuns(organizationId, taxYear, employeeId);
    if (runs.length === 0) {
      throw new NotFoundException(
        `No finalized payroll found for this employee in FY ${taxYear}.`,
      );
    }
    const statements = await this.scopedPrisma.tdsStatement.findMany({
      where: { organizationId, financialYear: taxYear },
    });
    // An employee only gets the certificate once the year's last statement is on record; HR can always prepare it.
    if (!isHr && !statements.some((s) => s.quarter === 4)) {
      throw new ForbiddenException(
        `Your Form 130 for FY ${taxYear} is not available yet — it is issued after the year's TDS statements are filed.`,
      );
    }
    const person = this.annualFromRuns(runs)[0];
    const org = await this.scopedPrisma.organization.findFirst({
      where: { id: organizationId },
      select: {
        companyName: true,
        legalName: true,
        tan: true,
        pan: true,
        registeredAddress: true,
        corporateAddress: true,
        contactEmail: true,
        phone: true,
      },
    });
    const challans = await this.scopedPrisma.tdsChallan.findMany({
      where: { organizationId, financialYear: taxYear },
    });
    const pd =
      (await this.personalDataById(organizationId, [employeeId])).get(
        employeeId,
      ) ?? {};
    const startYear = Number(taxYear.slice(0, 4));
    const orgRuns = await this.scopedPrisma.payrollRun.findMany({
      where: {
        organizationId,
        status: { in: PAID_OUT },
        OR: [
          { year: startYear, month: { gte: 4 } },
          { year: startYear + 1, month: { lte: 3 } },
        ],
      },
      select: { month: true, year: true, deductions: true },
    });
    const orgMonthTds = new Map<string, number>();
    for (const r of orgRuns) {
      const k = `${r.year}-${r.month}`;
      orgMonthTds.set(k, (orgMonthTds.get(k) ?? 0) + tdsOf(r.deductions));
    }
    const quarters = ([1, 2, 3, 4] as TdsQuarter[]).map((q) => {
      const ms = monthsOfQuarter(taxYear, q);
      let amountPaid = 0,
        tdsDeducted = 0,
        tdsDeposited = 0;
      for (const m of ms) {
        const mRuns = runs.filter(
          (r) => r.month === m.month && r.year === m.year,
        );
        const empTds = mRuns.reduce((s, r) => s + tdsOf(r.deductions), 0);
        amountPaid += mRuns.reduce(
          (s, r) => s + (r.taxableGross ?? r.grossSalary),
          0,
        );
        tdsDeducted += empTds;
        // Org-wide challans for the month cover that month's deductions pro rata.
        const monthTotal = orgMonthTds.get(`${m.year}-${m.month}`) ?? 0;
        const dep = challans
          .filter((c) => c.month === m.month && c.year === m.year)
          .reduce((s, c) => s + c.tdsAmount, 0);
        tdsDeposited +=
          monthTotal > 0
            ? Math.round(empTds * Math.min(1, dep / monthTotal))
            : 0;
      }
      const st = statements.find((s) => s.quarter === q);
      return {
        quarter: q,
        receiptNumber: st?.receiptNumber ?? null,
        formType: st?.formType ?? null,
        amountPaid,
        tdsDeducted,
        tdsDeposited,
      };
    });
    const d = person.details;
    const deductions = d?.deductions ?? {};
    const chapter6a = Object.entries(deductions).filter(
      ([k]) => k !== 'standard',
    );
    return {
      financialYear: taxYear,
      formName: Number(taxYear.slice(0, 4)) >= 2026 ? 'Form 130' : 'Form 16',
      employer: {
        name: org?.legalName || org?.companyName || '-',
        address: org?.registeredAddress || org?.corporateAddress || '-',
        pan: org?.pan || '-',
        tan: org?.tan || '-',
        email: org?.contactEmail || '-',
        phone: org?.phone || '-',
      },
      employee: {
        name: person.employee.name,
        code: person.employee.employeeId,
        designation: person.employee.designation,
        pan:
          typeof pd.panNumber === 'string' && pd.panNumber ? pd.panNumber : '-',
        address:
          typeof pd.currentAddress === 'string' && pd.currentAddress
            ? pd.currentAddress
            : '-',
      },
      period: {
        from: `${person.first.year}-${pad(person.first.month)}-01`,
        to: `${person.last.year}-${pad(person.last.month)}-${pad(new Date(Date.UTC(person.last.year, person.last.month, 0)).getUTCDate())}`,
      },
      quarters,
      totals: {
        amountPaid: quarters.reduce((s, q) => s + q.amountPaid, 0),
        tdsDeducted: quarters.reduce((s, q) => s + q.tdsDeducted, 0),
        tdsDeposited: quarters.reduce((s, q) => s + q.tdsDeposited, 0),
      },
      annexure: {
        regime: d?.regime ?? '-',
        grossSalary: person.gross,
        taxableSalary: person.taxableSalary,
        grossTotalIncome: d?.grossAnnualIncome ?? person.taxableSalary,
        exemptionHra: d?.exemptions?.hra ?? 0,
        exemptionLta: d?.exemptions?.lta ?? 0,
        standardDeduction: deductions.standard ?? 0,
        chapter6a: chapter6a
          .map(([k, v]) => ({ section: k, amount: v }))
          .filter((x) => x.amount > 0),
        totalIncome: d?.taxableIncome ?? 0,
        taxOnIncome: d?.taxBeforeCess ?? 0,
        rebate: d?.rebate ?? 0,
        surcharge: d?.surcharge ?? 0,
        cess: d?.cess ?? 0,
        relief89: d?.relief89 ?? 0,
        netTaxPayable: d?.totalAnnualTax ?? 0,
        previousEmployerTds: d?.previousEmployerTDS ?? 0,
        tdsDeducted: person.tds,
        balance:
          (d?.totalAnnualTax ?? 0) - (d?.previousEmployerTDS ?? 0) - person.tds,
      },
      issuedAt: new Date().toISOString().slice(0, 10),
      traces: statements.some((s) => s.quarter === 4),
    };
  }
